-- Signs that users ask the administrators to add
CREATE TABLE sign_request (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requester_id BIGINT        NOT NULL REFERENCES account (id) ON DELETE CASCADE,
    word         VARCHAR(100)  NOT NULL,
    -- sign language: FRENCH, GERMAN, ITALIAN
    language     VARCHAR(16)   NOT NULL,
    comment      VARCHAR(1000),
    -- OPEN, ADDED or REJECTED
    status       VARCHAR(16)   NOT NULL,
    -- the sign added for the request
    sign_uid     VARCHAR(64),
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    resolved_at  TIMESTAMP WITH TIME ZONE
);

CREATE INDEX sign_request_status ON sign_request (status, created_at);
