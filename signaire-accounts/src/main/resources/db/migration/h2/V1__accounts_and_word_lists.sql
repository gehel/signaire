-- The H2 version of postgresql/V1, for the standalone application: keep both in line.
CREATE TABLE account (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(40)  NOT NULL UNIQUE,
    display_name  VARCHAR(100) NOT NULL,
    -- null for accounts that log in with OpenID Connect only
    password_hash VARCHAR(255),
    oidc_issuer   VARCHAR(255),
    oidc_subject  VARCHAR(255),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT account_oidc_identity UNIQUE (oidc_issuer, oidc_subject)
);

CREATE TABLE word_list (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id   BIGINT       NOT NULL REFERENCES account (id) ON DELETE CASCADE,
    name       VARCHAR(100) NOT NULL,
    -- H2 has no index on expressions: the unique lower case name is a generated column
    name_key   VARCHAR(100) GENERATED ALWAYS AS (LOWER(name)),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE UNIQUE INDEX word_list_owner_name ON word_list (owner_id, name_key);

CREATE TABLE word_list_entry (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    word_list_id BIGINT      NOT NULL REFERENCES word_list (id) ON DELETE CASCADE,
    -- SignSuisse uid: signs live in the search index, rebuilt from the bundles
    sign_uid     VARCHAR(32) NOT NULL,
    added_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT word_list_entry_sign UNIQUE (word_list_id, sign_uid)
);

CREATE INDEX word_list_entry_sign_uid ON word_list_entry (sign_uid);
